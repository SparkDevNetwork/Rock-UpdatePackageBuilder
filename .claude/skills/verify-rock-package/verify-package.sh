#!/usr/bin/env bash
#
# Checks that a Rock update package leaves every release allowed to install it with the same RockWeb files as the
# target, then (with -p) checks the package itself: theme override files, source commit and zip. Read-only toward the
# package. Run from Git Bash.
#
# Usage:
#   verify-package.sh -r <rock repo> -m <minimum version tag> -t <target ref> -v <target version>
#                     [-p <rockpkg>] [-w <compiled target RockWeb>] [-s <sibling release tags>]
#                     [-x <exclude tag regex>] [-o <output dir>]
#
#   -r  Path to a Rock git checkout with all release tags fetched.
#   -m  Required (minimum) version tag, e.g. 17.6.1. The package must be built from this same tag.
#   -t  Release tag of the target, e.g. 19.8.1-alpha.
#   -v  Target version number, e.g. 18.8. Release tags at or above this are not checked.
#   -p  Built .rockpkg to check. Without it, the package is simulated from the git diff of minimum to target.
#   -w  Compiled RockWeb of the target. Leftover files it has are generated by the build, not left behind.
#   -s  Space-separated release tags of other majors shipping at the same time, e.g. "18.8.1-alpha". Pre-release
#       tags are otherwise skipped, so these are checked explicitly.
#   -x  Regex of release tags to skip (pre-release builds no site runs).
#   -o  Folder for the per-version file lists. Defaults to ./verify-output.
#
# Exit code is 1 when any check fails.

set -euo pipefail

repo=""; minimum=""; target=""; targetVersion=""; package=""; rockWeb=""; siblings=""; exclude='^$'
output="./verify-output"

while getopts "r:m:t:v:p:w:s:x:o:" option; do
    case $option in
        r) repo=$OPTARG ;;
        m) minimum=$OPTARG ;;
        t) target=$OPTARG ;;
        v) targetVersion=$OPTARG ;;
        p) package=$OPTARG ;;
        w) rockWeb=$OPTARG ;;
        s) siblings=$OPTARG ;;
        x) exclude=$OPTARG ;;
        o) output=$OPTARG ;;
        *) sed -n '3,24p' "$0"; exit 2 ;;
    esac
done

if [[ -z $repo || -z $minimum || -z $target || -z $targetVersion ]]; then
    sed -n '3,24p' "$0"
    exit 2
fi

mkdir -p "$output"

# Files the package never needs to carry: Bin is rebuilt wholesale, web.config is handled by the xdt transform, and
# theme override files belong to the site.
filterRockWeb() {
    grep '^rockweb/' \
        | grep -v -E '^rockweb/bin/|^rockweb/web\.config$|\.gitignore$|themes?/.*/styles/_.*override.*\.less$' \
        | sort -u || true
}

lower() {
    tr '[:upper:]' '[:lower:]'
}

# Files added or changed between two refs.
changedFiles() {
    git -C "$repo" diff --no-renames --name-only --diff-filter=AM "$1" "$2" | lower | filterRockWeb
}

# Files present in the first ref but removed by the second.
removedFiles() {
    git -C "$repo" diff --no-renames --name-only --diff-filter=D "$1" "$2" | lower | filterRockWeb
}

# Succeeds when version $1 sorts at or below version $2.
versionAtOrBelow() {
    [[ $(printf '%s\n%s\n' "$1" "$2" | sort -V | head -1) == "$1" ]]
}

if [[ -n $package ]]; then
    unzip -Z1 "$package" | grep '^content/' | grep -v '/$' | sed 's#^content/#RockWeb/#' | lower | filterRockWeb \
        > "$output/package-files.txt"
    unzip -p "$package" install/deletefile.lst 2>/dev/null | tr -d '\r' | tr '\\' '/' | lower | filterRockWeb \
        > "$output/package-deletes.txt"
    source="package $(basename "$package")"
else
    changedFiles "$minimum" "$target" > "$output/package-files.txt"
    removedFiles "$minimum" "$target" > "$output/package-deletes.txt"
    source="simulated from $minimum"
fi

if [[ -n $rockWeb ]]; then
    (cd "$rockWeb/.." && find "$(basename "$rockWeb")" -type f) | sed 's#^[^/]*/#RockWeb/#' | lower | sort -u \
        > "$output/built.txt"
else
    : > "$output/built.txt"
fi

echo "Target $target ($targetVersion), minimum $minimum, $source"
echo "Package: $(wc -l < "$output/package-files.txt") files, $(wc -l < "$output/package-deletes.txt") deletes"
echo

allowedReleases=$(git -C "$repo" tag -l \
    | grep -E '^[0-9]+(\.[0-9]+)+$' \
    | grep -v -E "$exclude" \
    | sort -V \
    | while read -r tag; do
        if versionAtOrBelow "$minimum" "$tag" && ! versionAtOrBelow "$targetVersion" "$tag"; then
            echo "$tag"
        fi
    done)

failed=0
printf '%-14s %8s %8s %8s %10s\n' "Release" "Missing" "Stale" "Other" "Generated"

for release in $allowedReleases $siblings; do
    changedFiles "$release" "$target" | comm -23 - "$output/package-files.txt" > "$output/missing-$release.txt"

    # Leftovers the compiled target also has are generated by the build, not left behind.
    removedFiles "$release" "$target" | comm -23 - "$output/package-deletes.txt" > "$output/leftover-$release.txt"
    comm -12 "$output/leftover-$release.txt" "$output/built.txt" > "$output/generated-$release.txt"
    comm -23 "$output/leftover-$release.txt" "$output/built.txt" > "$output/stale-$release.txt"

    missing=$(wc -l < "$output/missing-$release.txt")
    stale=$(wc -l < "$output/stale-$release.txt")
    generated=$(wc -l < "$output/generated-$release.txt")

    # Stale block files (.ascx and .ascx.cs) are usually removed by the chop job after the update; anything else is not.
    staleOther=$(grep -c -v -E '\.ascx(\.cs)?$' "$output/stale-$release.txt" || true)

    printf '%-14s %8s %8s %8s %10s\n' "$release" "$missing" "$stale" "$staleOther" "$generated"

    if (( missing > 0 )); then
        failed=1
    fi
done

echo
echo "File lists: $output"

if [[ -z $package ]]; then
    exit $failed
fi

echo
echo "Package checks"

# Source: the build must have the target's files, and the target must match origin's tag (or branch). Commits that
# change no files (e.g. a merge) don't count.
targetCommit=$(git -C "$repo" rev-parse --short "$target^{commit}")
remoteCommit=$(git -C "$repo" ls-remote origin "refs/tags/$target^{}" "refs/tags/$target" "refs/heads/$target" \
    2>/dev/null | sort -k2,2r | head -1 | cut -c1-${#targetCommit} || true)
checkoutCommit=$(git -C "$repo" rev-parse --short HEAD)
if [[ -n $remoteCommit && $remoteCommit != "$targetCommit" ]]; then
    echo "  FAIL source: $target is $targetCommit locally but $remoteCommit on origin. Fetch and rebuild."
    failed=1
elif ! git -C "$repo" diff --quiet "$checkoutCommit" "$target" -- 2>/dev/null; then
    echo "  FAIL source: the checkout ($checkoutCommit) has different files from $target ($targetCommit)."
    failed=1
else
    echo "  ok   source: built from $target at $targetCommit${remoteCommit:+ (matches origin)}."
fi

# Zip integrity.
if unzip -tq "$package" > /dev/null 2>&1; then
    echo "  ok   zip: no errors."
else
    echo "  FAIL zip: unzip -t reports errors."
    failed=1
fi

# Theme override files belong to the site, except in a theme the minimum doesn't have.
overrides=$(unzip -Z1 "$package" | grep -i -E '^content/Themes/[^/]+/Styles/_(css|variable)-overrides\.less$' || true)
badOverrides=""
for file in $overrides; do
    theme=$(echo "$file" | cut -d/ -f3)
    if git -C "$repo" cat-file -e "$minimum:RockWeb/Themes/$theme" 2>/dev/null; then
        badOverrides="$badOverrides $file"
    fi
done
if [[ -n $badOverrides ]]; then
    echo "  FAIL overrides: remove these; they would overwrite a site's theme settings:"
    printf '         %s\n' $badOverrides
    failed=1
else
    echo "  ok   overrides: no theme override files for existing themes."
fi

exit $failed
